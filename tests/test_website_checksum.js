const assert=require('node:assert/strict'),fs=require('node:fs'),vm=require('node:vm'),crypto=require('node:crypto');
const nodes=new Map();
const get=id=>{if(!nodes.has(id))nodes.set(id,{dataset:{},value:'',textContent:'',events:{},addEventListener(k,fn){this.events[k]=fn},showModal(){this.open=true},close(){this.open=false;this.events.close?.()}});return nodes.get(id)};
const exeHash=JSON.parse(fs.readFileSync('website/dist/release.json','utf8')).sha256;
const zipHash=crypto.createHash('sha256').update(fs.readFileSync('website/dist/downloads/Pulse-Windows-x64.zip')).digest('hex');
get('#verify-download').dataset={exeHash,zipHash};get('#checksum-file').value='exe';
let copied='';const context={document:{querySelector:get},navigator:{clipboard:{writeText:async text=>copied=text}}};
vm.runInNewContext(fs.readFileSync('website/src/checksum.js','utf8'),context);
(async()=>{
 get('#open-checksum').events.click({preventDefault(){}});assert.equal(get('#verify-download').open,true);
 const exe=get('#checksum-command').textContent;
 assert.ok(exe.includes(exeHash));assert.ok(exe.includes("'.\\Pulse.exe'"));
 assert.ok(exe.includes('DOES NOT MATCH'));assert.ok(exe.includes('-ErrorAction Stop'));
 fs.mkdirSync('build',{recursive:true});fs.writeFileSync('build/check-exe-command.ps1',exe);
 fs.writeFileSync('build/check-mismatch-command.ps1',exe.replace(exeHash,'0'.repeat(64)));
 get('#checksum-file').value='zip';get('#checksum-file').events.change();
 const zip=get('#checksum-command').textContent;
 assert.ok(zip.includes(zipHash));assert.ok(zip.includes("'.\\Pulse-Windows-x64.zip'"));
 fs.writeFileSync('build/check-zip-command.ps1',zip);
 await get('#copy-checksum-command').events.click();assert.equal(copied,zip);
 await get('#copy-checksum').events.click();assert.equal(copied,zipHash);
 context.navigator.clipboard=null;await get('#copy-checksum-command').events.click();
 assert.ok(get('#checksum-status').textContent.includes('Clipboard access is unavailable'));
 get('#checksum-close').events.click();assert.equal(get('#verify-download').open,false);
 console.log('Command generation, release hashes, EXE/ZIP selection, copy fallback, and modal checks passed.');
})().catch(error=>{console.error(error);process.exitCode=1});
