const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const script=fs.readFileSync('website/src/theme.js','utf8');
function boot(saved,blocked=false){
  const root={dataset:{theme:'dark'}};
  const button={attributes:{},setAttribute(k,v){this.attributes[k]=v},addEventListener(_,fn){this.click=fn}};
  const meta={content:'#080b10'};
  const events={};
  let value=saved;
  const context={document:{documentElement:root,querySelector:s=>s==='#theme-toggle'?button:meta,addEventListener:(name,fn)=>events[name]=fn},window:{addEventListener:(name,fn)=>events[name]=fn},localStorage:{getItem(){if(blocked)throw Error('blocked');return value},setItem(_,next){if(blocked)throw Error('blocked');value=next}}};
  vm.runInNewContext(script,context);
  const beforeReady=root.dataset.theme;
  events.DOMContentLoaded();
  return {root,button,meta,events,beforeReady,saved:()=>value};
}
const first=boot(null);
assert.equal(first.beforeReady,'dark');
assert.equal(first.root.dataset.theme,'dark');
assert.equal(first.button.attributes['aria-label'],'Switch to light theme');
first.button.click();
assert.equal(first.root.dataset.theme,'light');
assert.equal(first.saved(),'light');
assert.equal(first.meta.content,'#f5f7fb');
assert.equal(first.button.attributes['aria-label'],'Switch to dark theme');
const restored=boot(first.saved());
assert.equal(restored.beforeReady,'light','Saved light theme must apply before DOM ready');
restored.button.click();
assert.equal(restored.root.dataset.theme,'dark');
assert.equal(restored.saved(),'dark');
assert.equal(boot('invalid').root.dataset.theme,'dark');
const blocked=boot(null,true);
assert.equal(blocked.root.dataset.theme,'dark');
blocked.button.click();
assert.equal(blocked.root.dataset.theme,'light','Theme switching must work when persistence is blocked');
first.events.storage({key:'pulse.website.theme',newValue:'dark'});
assert.equal(first.root.dataset.theme,'dark');
first.events.storage({key:null,newValue:null});
assert.equal(first.root.dataset.theme,'dark');
console.log('Website dark default, early restoration, theme toggle, persistence, cross-tab sync, and blocked-storage checks passed.');
